// Builds lib/guideAgents.generated.ts: which agent slugs each guide covers.
//
// Every guide page declares the listings it covers in a `GUIDE_SLUGS = [...]` line. Site search
// uses this map to show "Pages that cover <agent>" - the guides are TSX files, not database rows,
// so search cannot read their text. This runs before every build (package.json "build"), so a new
// or edited guide is picked up without anyone having to remember. Added 2026-11-13.
//
// It fails the build (exit 1) if a guide's list cannot be read, rather than silently publishing a
// map that leaves guides out - a failed build keeps the last good deployment live.
import { readdirSync, readFileSync, writeFileSync, existsSync } from 'node:fs'
import { join } from 'node:path'

const GUIDES_DIR = 'app/resources/guides'
const OUT = 'lib/guideAgents.generated.ts'

const map = {}
for (const entry of readdirSync(GUIDES_DIR, { withFileTypes: true })) {
  if (!entry.isDirectory()) continue
  const file = join(GUIDES_DIR, entry.name, 'page.tsx')
  if (!existsSync(file)) continue
  const src = readFileSync(file, 'utf8')
  const m = src.match(/GUIDE_SLUGS\s*(?::[^=]+)?=\s*\[([^\]]*)\]/)
  if (!m) continue // a guide with no agent list (e.g. a how-to) simply covers no listings
  const slugs = [...m[1].matchAll(/['"]([a-z0-9-]+)['"]/g)].map((x) => x[1])
  if (slugs.length === 0 && m[1].trim() !== '') {
    console.error(`gen-guide-agents: could not read the GUIDE_SLUGS list in ${file}`)
    process.exit(1)
  }
  map[entry.name] = slugs
}

const body =
  '// GENERATED by scripts/gen-guide-agents.mjs before every build. Do not edit by hand.\n' +
  '// guide slug -> agent slugs that guide covers (from each guide page\'s GUIDE_SLUGS line).\n' +
  'export const GUIDE_AGENTS: Record<string, string[]> = ' +
  JSON.stringify(map, null, 2) +
  '\n'
writeFileSync(OUT, body)
console.log(`gen-guide-agents: ${Object.keys(map).length} guides, ${Object.values(map).reduce((n, a) => n + a.length, 0)} agent links -> ${OUT}`)
